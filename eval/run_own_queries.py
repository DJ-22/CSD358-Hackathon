"""Run S0 and S5 on the team's hand-judged own queries and report P@2 / P@10."""
import sys, pathlib  # bootstrap: make the repo root importable
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import json

import config
from eval.metrics import p_at_k

OWN_QUERIES = config.ROOT / "data" / "own_queries.jsonl"
OUT_PATH = config.RESULTS_DIR / "own_queries.md"
SYSTEMS = ("S0", "S5")
EXAMPLE = {"qid": "own-00", "question": "EXAMPLE — replace me", "gold_titles": ["TODO", "TODO"]}


def is_placeholder(q: dict) -> bool:
    """True for the example line or any line whose judgements are still TODO."""
    return q["question"].startswith("EXAMPLE") or any(t == "TODO" for t in q["gold_titles"])


def load_own_queries() -> list[dict]:
    """Read data/own_queries.jsonl: one {"qid", "question", "gold_titles"} per line (qid optional)."""
    out = []
    with open(OWN_QUERIES, encoding="utf-8") as f:
        for i, line in enumerate(f, start=1):
            if line.strip():
                q = json.loads(line)
                q.setdefault("qid", f"own-{i:02d}")
                out.append(q)
    return out


def main() -> None:
    """Precision@k on own judged queries."""
    if not OWN_QUERIES.exists():
        OWN_QUERIES.write_text(json.dumps(EXAMPLE, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"created {OWN_QUERIES.relative_to(config.ROOT)} with one example line.\n"
              "Replace it with 15 hand-written questions, each judged with the exact titles of its relevant "
              "paragraphs in the dev corpus (data/processed/title2doc_dev.json), then re-run.")
        return
    queries = [q for q in load_own_queries() if not is_placeholder(q)]
    if not queries:
        print(f"{OWN_QUERIES.relative_to(config.ROOT)} only has placeholder lines: add judged questions first.")
        return

    from agent.pipeline import run_system
    from agent.resources import load_resources
    res = load_resources("dev", with_ranker=True)
    unknown = [(q["qid"], t) for q in queries for t in q["gold_titles"] if t not in res.title2doc]
    if unknown:
        raise SystemExit("gold titles not in the dev corpus (must match a title exactly):\n"
                         + "\n".join(f"  {qid}: {t}" for qid, t in unknown))

    rows = []
    for q in queries:
        gold = [res.title2doc[t] for t in q["gold_titles"]]
        row = {"qid": q["qid"], "question": q["question"]}
        for name in SYSTEMS:
            ranking, _ = run_system(q, dict(config.SYSTEMS[name]), res)
            docs = [int(d) for d, _ in ranking]
            row[name] = (p_at_k(docs, gold, 2), p_at_k(docs, gold, 10))
        rows.append(row)

    n = len(rows)
    mean = {name: (sum(r[name][0] for r in rows) / n, sum(r[name][1] for r in rows) / n) for name in SYSTEMS}
    lines = ["# Own queries: S0 vs S5", "",
             f"{n} hand-written questions with team-judged relevant titles (`data/own_queries.jsonl`), "
             "retrieved from the dev corpus.", "",
             "| qid | question | S0 P@2 | S0 P@10 | S5 P@2 | S5 P@10 |", "|---|---|---|---|---|---|"]
    for r in rows:
        text = r["question"].replace("|", "\\|")
        lines.append(f"| {r['qid']} | {text} | " + " | ".join(f"{v:.2f}" for name in SYSTEMS for v in r[name]) + " |")
    lines.append("| **mean** | | " + " | ".join(f"**{v:.3f}**" for name in SYSTEMS for v in mean[name]) + " |")
    lines += ["", "Generated by `python eval/run_own_queries.py`."]
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
